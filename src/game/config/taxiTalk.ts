/** Pick a line without repeating the last one used for the same situation. */
export function pickTalk(id: TalkId, last: Map<TalkId, number>, rng: () => number): string {
  const lines = TALK[id];
  let i = Math.floor(rng() * lines.length);
  if (lines.length > 1 && i === last.get(id)) i = (i + 1) % lines.length;
  last.set(id, i);
  return lines[i]!;
}
