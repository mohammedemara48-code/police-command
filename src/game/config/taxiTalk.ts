export function fill(line: string, vars: { to?: string; from?: string }): string {
  return line
    .replaceAll('{to}', (vars.to ?? '').replace(/^موقف /, ''))
    .replaceAll('{from}', (vars.from ?? '').replace(/^موقف /, ''));
}

